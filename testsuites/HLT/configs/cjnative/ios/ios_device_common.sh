# Common utility functions for the iOS real-device direct-executable route.
# Sourced by each run script to avoid duplicated code.
#
# Unlike the simulator, a real device cannot spawn an arbitrary binary: every
# executable must be packaged as a minimal .app, signed with a real development
# certificate and installed before it can run. These helpers do exactly that
# without ever invoking xcodebuild, so no Xcode project/scheme is needed -- only
# the command line tools that ship with Xcode (codesign, otool,
# install_name_tool, plutil, devicectl) and, optionally, libimobiledevice.
#
# One-time setup environment variables:
#   CANGJIE_HOME                           (required) cangjie SDK root.
#   IOS_DEVICE_PROVISION_PROFILE           (required) path to a .mobileprovision
#                                          that (a) includes the target device
#                                          UDID and (b) was issued for a
#                                          certificate present in the keychain.
#                                          Reuse the profile generated by any
#                                          Xcode development build. Mind its
#                                          ExpirationDate (7 days for a free
#                                          account, 1 year for a paid team).
#   XCODE_DEVICE_UDID_OF_CANGJIE_IOS_TEST  (optional) target device UDID;
#                                          defaults to the first connected
#                                          device reported by
#                                          `xcrun devicectl list devices`.
#   IOS_DEVICE_SIGN_IDENTITY               (optional) codesign identity (name or
#                                          SHA-1); defaults to the first valid
#                                          "Apple Development" identity in the
#                                          keychain.
#   IOS_DEVICE_BUNDLE_ID                   (optional) fixed bundle id; defaults
#                                          to the one encoded in the profile,
#                                          or, when the profile is a wildcard,
#                                          a per-work_dir id (so parallel cases
#                                          cannot clobber each other's install).
#   IOS_DEVICE_MIN_OS_VERSION              (optional) MinimumOSVersion of the
#                                          generated Info.plist, default 12.0.
#   IOS_DEVICE_LAUNCH_MODE                 (optional) auto|devicectl|idevicedebug,
#                                          default auto: prefer `devicectl ...
#                                          --console` (Xcode 16+), fall back to
#                                          libimobiledevice's idevicedebug.
#   IOS_DEVICE_NO_CHATTER_FILTER           (optional) set to 1 to disable the
#                                          timestamp-line chatter filter applied
#                                          to devicectl --console output.
#
# All diagnostics go to stderr; stdout is reserved for the case output the
# framework compares. Keep the code compatible with macOS /bin/bash 3.2 (no
# associative arrays, no "${var,,}", no ";&;").

USED_LAUNCH_MODE=unknown

# Check CANGJIE_HOME
require_cangjie_home() {
    if [ -z "${CANGJIE_HOME}" ]; then
        echo "Error: CANGJIE_HOME is not set" >&2
        return 255
    fi
    return 0
}

# Detect whether a file is a Mach-O dynamic library (by content, not suffix),
# so actual dylibs named *.a are also handled.
is_macho_dylib() {
    [ -f "$1" ] || return 1
    file -b "$1" 2>/dev/null | grep -qE "Mach-O.*(dylib|dynamically linked shared library)"
}

# Return the first valid "Apple Development" codesign identity (SHA-1 hash).
find_sign_identity() {
    security find-identity -v -p codesigning 2>/dev/null |
        awk '/Apple Development/ {print $2; exit}'
}

# Output a usable device UDID: prefer the environment variable, otherwise the
# first connected/available device reported by devicectl. Device identifiers
# come in two shapes (00008101-XXXXXXXXXXXXXX or a full UUID), match both.
get_device_udid() {
    local udid="${XCODE_DEVICE_UDID_OF_CANGJIE_IOS_TEST}"
    if [ -z "$udid" ]; then
        udid=$(xcrun devicectl list devices 2>/dev/null |
            grep -Ew 'connected|available' |
            grep -Eo '([0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}|[0-9A-Fa-f]{8}-[0-9A-Fa-f]{12,16})' |
            head -n 1)
    fi
    if [ -z "$udid" ]; then
        echo "Error: no connected iOS device; set XCODE_DEVICE_UDID_OF_CANGJIE_IOS_TEST or connect a device" >&2
        return 255
    fi
    echo "$udid"
}

# Decode the provisioning profile, extract its entitlements for re-signing and
# derive the bundle id. Sets the globals SIGN_IDENTITY and BUNDLE_ID.
# Usage: prepare_signing <profile-path> <work-dir-for-temp-files>
prepare_signing() {
    local profile="$1" work="$2"
    if [ -z "$profile" ] || [ ! -f "$profile" ]; then
        echo "Error: IOS_DEVICE_PROVISION_PROFILE is not set or not a file; a development provisioning profile covering the device is required for on-device signing" >&2
        return 255
    fi
    SIGN_IDENTITY=$(find_sign_identity)
    if [ -z "$SIGN_IDENTITY" ]; then
        echo "Error: no valid 'Apple Development' identity in the keychain; set IOS_DEVICE_SIGN_IDENTITY" >&2
        return 255
    fi
    if ! security cms -D -i "$profile" > "$work/profile.plist" 2>/dev/null; then
        echo "Error: cannot decode provisioning profile '$profile'" >&2
        return 255
    fi
    if ! plutil -extract Entitlements xml1 -o "$work/entitlements.plist" "$work/profile.plist" 2>/dev/null; then
        echo "Error: no Entitlements found in the provisioning profile" >&2
        return 255
    fi
    # application-identifier looks like "TEAMID.com.example.app" or "TEAMID.*".
    local appid default_bid
    appid=$(plutil -extract Entitlements.application-identifier raw -o - "$work/profile.plist" 2>/dev/null | head -n 1 | tr -d '[:space:]')
    default_bid="${appid#*.}"
    if [ -n "${IOS_DEVICE_BUNDLE_ID:-}" ]; then
        BUNDLE_ID="$IOS_DEVICE_BUNDLE_ID"
    elif [ -z "$default_bid" ] || [ "$default_bid" = "*" ]; then
        # Wildcard profile: give each case its own bundle id derived from the
        # work_dir, so concurrent cases don't race on one installed app.
        BUNDLE_ID="com.cangjie.ios-exe-test.$(printf '%s' "$(pwd)" | cksum | awk '{print $1}')"
    else
        BUNDLE_ID="$default_bid"
    fi
    local exp
    exp=$(plutil -extract ExpirationDate raw -o - "$work/profile.plist" 2>/dev/null | head -n 1 | tr -d '[:space:]')
    echo "signing identity: $SIGN_IDENTITY" >&2
    echo "bundle id: $BUNDLE_ID" >&2
    if [ -n "$exp" ]; then
        echo "profile expires: $exp" >&2
    fi
    return 0
}

# Generate the minimal Info.plist for the wrapper app.
# Usage: generate_info_plist <output-path>   (uses the global BUNDLE_ID)
generate_info_plist() {
    cat > "$1" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>CFBundleExecutable</key><string>main</string>
	<key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleName</key><string>main</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>1.0</string>
	<key>CFBundleSupportedPlatforms</key><array><string>iPhoneOS</string></array>
	<key>CFBundleVersion</key><string>1</string>
	<key>LSRequiresIPhoneOS</key><true/>
	<key>MinimumOSVersion</key><string>${IOS_DEVICE_MIN_OS_VERSION:-12.0}</string>
	<key>UIDeviceFamily</key><array><integer>1</integer></array>
</dict>
</plist>
EOF
}

# Find a file by name inside a (space-separated) list of directories.
find_in_dirs() {
    local name="$1" dirs="$2" d
    for d in $dirs; do
        if [ -f "$d/$name" ]; then
            echo "$d/$name"
            return 0
        fi
    done
    return 1
}

# Collect the dynamic library dependencies of $1 and bundle them under the
# app's Frameworks directory, rewriting references to @rpath so dyld resolves
# them inside the .app (a real device has neither the work_dir nor a usable
# DYLD_LIBRARY_PATH). Non-system references whose file exists on the build
# host are rewritten to @rpath/<basename>; already-@rpath references (SDK
# dylibs) are resolved by searching the runtime/STDX/work directories.
# System libraries under /usr/lib and /System are left alone: the device
# provides them itself. Anything not found locally is reported and left as-is.
# Usage: bundle_dylib_deps <executable-in-app> <Frameworks-dir>
bundle_dylib_deps() {
    local exe="$1" fw="$2"
    local search_dirs="$(pwd) ${CANGJIE_HOME}/runtime/lib/ios_aarch64_cjnative"
    if [ -n "${CANGJIE_STDX_PATH:-}" ]; then
        search_dirs="$search_dirs $CANGJIE_STDX_PATH"
    fi

    local queue=("$exe")
    local seen=" $exe "
    local idx=0
    while [ "$idx" -lt "${#queue[@]}" ]; do
        local f="${queue[$idx]}"
        idx=$((idx + 1))
        [ -e "$f" ] || continue
        local deps dep
        deps=$(otool -L "$f" 2>/dev/null | tail -n +2 | awk '{print $1}') || continue
        for dep in $deps; do
            local resolved="" base
            base=$(basename "$dep")
            case "$dep" in
                @rpath/*)
                    resolved=$(find_in_dirs "$base" "$search_dirs" || true)
                    ;;
                @executable_path/*|@loader_path/*)
                    continue
                    ;;
                /usr/lib/system/*|/System/*|/usr/lib/*)
                    continue
                    ;;
                *)
                    if [ -f "$dep" ]; then
                        resolved="$dep"
                    else
                        resolved=$(find_in_dirs "$base" "$search_dirs" || true)
                    fi
                    if [ -n "$resolved" ]; then
                        install_name_tool -change "$dep" "@rpath/$base" "$f" 2>/dev/null || true
                    else
                        echo "Warning: dependency '$dep' of '$f' not found locally, left as-is (must exist on the device)" >&2
                        continue
                    fi
                    ;;
            esac
            [ -n "$resolved" ] || continue
            case "$seen" in
                *" $base "*) continue ;;
            esac
            is_macho_dylib "$resolved" || continue
            seen="$seen$base "
            local dst="$fw/$base"
            cp -f "$resolved" "$dst"
            install_name_tool -id "@rpath/$base" "$dst" 2>/dev/null || true
            # Give the dylib its own rpath as well: dyld resolves @rpath against
            # the loading image's rpaths, and both interpretations are covered.
            install_name_tool -add_rpath @executable_path/Frameworks "$dst" 2>/dev/null || true
            queue+=("$dst")
        done
    done
    echo "bundled dynamic libraries: $(ls "$fw" 2>/dev/null | wc -l | tr -d ' ')" >&2
}

# Add the Frameworks rpath to the app's main executable (no-op if present).
add_bundle_rpath() {
    install_name_tool -add_rpath @executable_path/Frameworks "$1" 2>/dev/null || true
}

# Sign all nested dylibs first, then seal the app bundle, with the entitlements
# extracted from the provisioning profile. Ad-hoc signing (as on the simulator)
# is rejected on real devices, so a real identity is mandatory here.
# Usage: sign_bundle <app-dir> <identity> <entitlements-plist>
sign_bundle() {
    local app_dir="$1" identity="$2" ent="$3"
    local f
    if [ -d "$app_dir/Frameworks" ]; then
        for f in "$app_dir/Frameworks"/*; do
            [ -e "$f" ] || continue
            codesign -f -s "$identity" --timestamp=none --entitlements "$ent" "$f" || return 255
        done
    fi
    codesign -f -s "$identity" --timestamp=none --entitlements "$ent" "$app_dir" || return 255
}

# Whether this devicectl supports the --console option (Xcode 16+), which
# streams the app's stdout/stderr back to the launch command.
devicectl_has_console() {
    xcrun devicectl device process launch --help 2>&1 | grep -q -- '--console'
}

# Launch the installed app and capture its output into a file. Sets the global
# USED_LAUNCH_MODE to the channel actually used. Without any stdout channel
# the framework could false-pass on empty output, so fail hard instead.
# Usage: launch_and_capture <udid> <bundle-id> <output-file> [app-args...]
launch_and_capture() {
    local udid="$1" bid="$2" out="$3"
    shift 3
    local mode="${IOS_DEVICE_LAUNCH_MODE:-auto}"
    if [ "$mode" = "auto" ] || [ "$mode" = "devicectl" ]; then
        if devicectl_has_console; then
            USED_LAUNCH_MODE=devicectl
            echo "launching '$bid' on device $udid via devicectl --console" >&2
            xcrun devicectl device process launch --device "$udid" --terminate-existing --console "$bid" "$@" > "$out" 2>&1
            return $?
        fi
        if [ "$mode" = "devicectl" ]; then
            echo "Error: this devicectl does not support '--console'; upgrade to Xcode 16+ or set IOS_DEVICE_LAUNCH_MODE=idevicedebug" >&2
            return 255
        fi
    fi
    if command -v idevicedebug > /dev/null 2>&1; then
        USED_LAUNCH_MODE=idevicedebug
        echo "launching '$bid' on device $udid via idevicedebug" >&2
        idevicedebug -u "$udid" run "$bid" "$@" > "$out" 2>&1
        return $?
    fi
    echo "Error: no stdout channel for on-device launch (devicectl lacks '--console' and idevicedebug is not installed). Install libimobiledevice or upgrade to Xcode 16+, otherwise case output cannot be captured." >&2
    return 255
}

# Drop devicectl's own console chatter so only the case output reaches the
# framework: timestamped banner/status lines, plus the untimestamped
# "Launched application with <bundle> bundle identifier." and "Waiting for
# the application to terminate…" banners observed with Xcode 26 devicectl
# --console (confirmed on first device run 2026-10-31). Only applied in
# devicectl mode; idevicedebug relays the app's output verbatim.
filter_chatter() {
    if [ "${IOS_DEVICE_NO_CHATTER_FILTER:-0}" = "1" ] || [ "$USED_LAUNCH_MODE" != "devicectl" ]; then
        cat
        return 0
    fi
    sed -E -e '/^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T]/d' \
           -e '/^[0-9]{2}:[0-9]{2}:[0-9]{2}([[:space:]]|$)/d' \
           -e '/^Launched application with .* bundle identifier\.?$/d' \
           -e '/^Waiting for the application to terminate/d'
}

# Resolve the case exit code, in priority order:
#   1. the cj_main_return marker printed by modify_cj_file_for_ios.py (the
#      wrapper added at compile time via cmp_opt) -- the authoritative channel;
#   2. an "exited with status N" / "exited abnormally with signal N" line from
#      the devicectl console;
#   3. the launch command's own non-zero exit code;
#   4. 255 with a warning (launch rc=0 and no marker at all).
# Usage: resolve_exit_code <output-file> <launch-rc>
resolve_exit_code() {
    local out="$1" rc="$2" ret=""
    ret=$(sed -n 's/.*cj_main_return_start\(-\{0,1\}[0-9]\{1,\}\)cj_main_return_end.*/\1/p' "$out" 2>/dev/null | tail -n 1)
    if [ -n "$ret" ]; then
        echo "$ret"
        return 0
    fi
    ret=$(sed -n 's/.*[Ee]xited with status \([0-9]\{1,\}\).*/\1/p' "$out" 2>/dev/null | tail -n 1)
    if [ -n "$ret" ]; then
        echo "$ret"
        return 0
    fi
    ret=$(grep -Ei 'exited abnormally with signal' "$out" 2>/dev/null | grep -Eo '[0-9]+' | tail -n 1)
    if [ -n "$ret" ]; then
        echo $((128 + ret))
        return 0
    fi
    if [ "$rc" -ne 0 ]; then
        echo "$rc"
        return 0
    fi
    echo "Warning: cannot determine the app exit code (no cj_main_return marker, no exit status line, launch rc=0); reporting 255" >&2
    echo 255
}
